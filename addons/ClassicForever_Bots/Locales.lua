ns.LangTables = { en = EN, es = ES }

function ns.SetLanguage(code)
    if code ~= "es" and code ~= "en" then
        local locale = GetLocale()
        code = (locale == "esES" or locale == "esMX") and "es" or "en"
    end
    ns.Lang = code
    ns.L = setmetatable({}, { __index = function(_, k) return (code == "es" and ES[k]) or EN[k] or k end })
end

function ns.DungeonName(d)
    return (ns.Lang == "es" and d.es) or d.en
end

ns.SetLanguage("auto")
